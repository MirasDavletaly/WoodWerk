/* Ставит на <html> класс js — по нему включается всё, что имеет смысл только
   при работающих скриптах: появление блоков при прокрутке.

   Файл подключён в <head> без defer, поэтому класс появляется до первой
   отрисовки и содержимое не успевает мигнуть.

   Смысл в обратном случае: если скрипты отключены, заблокированы расширением
   или упали с ошибкой, класса не будет — и страница покажется целиком.
   Раньше .reveal прятал блоки безусловно, и любая осечка в JS оставляла
   от главной пустой экран.

   Отдельным файлом, а не строкой в разметке: политика безопасности сайта
   разрешает только собственные скрипты (script-src 'self'), встроенный
   <script> браузер бы не выполнил. */
document.documentElement.classList.add('js');
